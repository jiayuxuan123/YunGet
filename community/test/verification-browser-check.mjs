async page => {
  const base='http://127.0.0.1:8803';
  const directory='output/playwright/community-mobile';
  const checks=[];const errors=[];const external=[];const timings=[];
  const check=(ok,label)=>{if(!ok)throw new Error(label);checks.push(label);};
  page.on('pageerror',error=>errors.push(error.message));
  page.on('request',request=>{if(!request.url().startsWith(base)&&!request.url().startsWith('data:'))external.push(request.url());});
  const verified=async()=>{
    const start=Date.now();
    await page.getByText('验证通过，可以提交',{exact:true}).waitFor({timeout:15000});
    timings.push(Date.now()-start);
    return page.locator('altcha-widget input[type=hidden]').inputValue();
  };
  await page.setViewportSize({width:320,height:740});await page.goto(base);
  await page.getByRole('button',{name:'设置社区昵称',exact:true}).click();
  const first=await verified();
  check(first.length>100,'the real widget produces a signed proof');
  await page.getByRole('button',{name:'重新验证',exact:true}).click();
  await page.getByRole('button',{name:'重新验证',exact:true}).click();
  const replacement=await verified();
  check(first!==replacement,'retry creates a fresh challenge');
  check(await page.locator('altcha-widget').count()===1,'rapid retries keep a single verification widget');
  await page.screenshot({path:directory+'/selfhost-320-light.png',animations:'disabled'});
  const bounds=await page.locator('#modal').evaluate(modal=>({available:modal.clientWidth,scroll:modal.scrollWidth}));
  check(bounds.scroll<=bounds.available,'verification fits a 320px phone');
  await page.locator('#nickname').fill('本地验证用户');
  const sessionResponse=page.waitForResponse(response=>response.url().endsWith('/api/session')&&response.request().method()==='POST');
  await page.getByRole('button',{name:'保存昵称',exact:true}).click();
  check((await sessionResponse).status()===201,'the Worker validates proof before creating a nickname session');
  await page.locator('#modal').waitFor({state:'hidden'});
  const session=await(await page.request.get(base+'/api/session')).json();
  check(Boolean(session.nickname),'the secure session remains usable after registration');
  const replay=await page.request.post(base+'/api/session',{headers:{Origin:base},data:{nickname:'重复验证',challenge:replacement}});
  check(replay.status()===403,'the real D1 database rejects a consumed proof');

  await page.getByRole('button',{name:'写反馈',exact:true}).click();
  await page.locator('#title').fill('本地自托管验证回归');
  await page.locator('#body').fill('验证器的正式前后端联调，只保存在本地测试数据库。');
  await page.locator('[name=private]').check();
  await page.getByRole('button',{name:'下一步',exact:true}).click();
  await verified();
  const feedbackResponse=page.waitForResponse(response=>response.url().endsWith('/api/feedback')&&response.request().method()==='POST');
  await page.locator('#verify-form [type=submit]').click();
  check((await feedbackResponse).status()===201,'feedback can be submitted with self-hosted verification');
  await page.locator('#modal').waitFor({state:'hidden'});
  await page.locator('.feedback-row').first().click();
  await page.locator('#reply').fill('本地回复验证。');
  await page.getByRole('button',{name:'发送回复',exact:true}).click();
  await verified();
  const replyResponse=page.waitForResponse(response=>response.url().includes('/replies')&&response.request().method()==='POST');
  await page.locator('#verify-form [type=submit]').click();
  check((await replyResponse).status()===201,'thread replies use their own verified write scope');
  await page.getByRole('heading',{name:'本地自托管验证回归',exact:true}).waitFor();
  await page.getByRole('button',{name:'关闭',exact:true}).click();
  await page.getByRole('button',{name:'闲聊',exact:true}).click();
  await page.locator('#chat-body').fill('本地聊天验证，未发布到正式社区。');
  await page.getByRole('button',{name:'发送消息',exact:true}).click();
  await verified();
  await page.route('**/api/verification/challenge?*',route=>route.abort(),{times:1});
  await page.getByRole('button',{name:'重新验证',exact:true}).click();
  await page.getByText('验证未完成，请点击重新验证',{exact:true}).waitFor();
  check(await page.locator('.verification-status').innerText()!=='验证通过，可以提交','a network error never retains a verified status');
  await page.getByRole('button',{name:'重新验证',exact:true}).click();
  await verified();
  await page.emulateMedia({colorScheme:'dark'});
  await page.screenshot({path:directory+'/selfhost-320-dark.png',animations:'disabled'});
  const chatResponse=page.waitForResponse(response=>response.url().endsWith('/api/chat')&&response.request().method()==='POST');
  await page.locator('#verify-form [type=submit]').click();
  check((await chatResponse).status()===201,'chat recovers from verification network failure and submits');
  await page.locator('#modal').waitFor({state:'hidden'});
  check(external.length===0,'all verification scripts, workers and HTTP calls stay on the community origin');
  check(errors.length===0,'no uncaught JavaScript errors');
  return {checks,count:checks.length,verification_wait_ms:timings,external,errors};
}
