async page => {
  const base = 'http://127.0.0.1:8801';
  const directory = 'output/playwright/community-mobile';
  const checks = [];
  const errors = [];
  const check = (condition, name) => { if (!condition) throw new Error(name); checks.push(name); };
  page.on('pageerror', error => errors.push(error.message));
  await page.request.post(base + '/test/control', {data: {resetIdentity: true}});
  const previousWriteCount=(await (await page.request.get(base + '/test/writes')).json()).length;
  const external=[];
  page.on('request',request=>{if(!request.url().startsWith(base)&&!request.url().startsWith('data:'))external.push(request.url());});
  const fit = async name => {
    const measurements = await page.evaluate(() => ({
      viewport: innerWidth, document: document.documentElement.scrollWidth,
      app: document.getElementById('app').scrollWidth, available: document.getElementById('app').clientWidth,
    }));
    check(measurements.document <= measurements.viewport && measurements.app <= measurements.available + 1, name + ' has no horizontal overflow');
  };
  await page.setViewportSize({width: 390, height: 844});
  await page.goto(base);
  await page.locator('.feedback-row').first().waitFor();
  await fit('phone feedback');
  check(await page.locator('#feedback-form').count() === 0, 'feedback list precedes the composer');
  await page.screenshot({animations: 'disabled', path: directory + '/feedback-light.png'});
  await page.getByRole('button', {name: '写反馈', exact: true}).click();
  await page.locator('#title').fill('手机界面反馈草稿');
  await page.locator('#body').fill('本地验证：关闭弹窗、设置昵称以及请求失败后，都需要保留完整草稿。');
  await page.locator('#category').selectOption('idea');
  await page.locator('#app_version').fill('2.7.28');
  await page.locator('[name=private]').check();
  await page.getByRole('button', {name: '下一步', exact: true}).click();
  await page.getByRole('heading', {name: '设置社区昵称'}).waitFor();
  await page.getByRole('button', {name: '关闭', exact: true}).click();
  await page.locator('#feedback-form').waitFor();
  check(await page.locator('#title').inputValue() === '手机界面反馈草稿', 'guest nickname cancellation restores the title');
  check(await page.locator('[name=private]').isChecked(), 'private feedback preference survives nickname step');
  check(await page.locator('#category').inputValue() === 'idea', 'category survives nickname step');
  await page.screenshot({animations: 'disabled', path: directory + '/feedback-composer.png'});
  await page.getByRole('button', {name: '下一步', exact: true}).click();
  await page.locator('#nickname').fill('本地测试昵称');
  await page.getByText('验证通过，可以提交', {exact: true}).waitFor();
  await page.getByRole('button', {name: '保存昵称', exact: true}).click();
  await page.getByRole('heading', {name: '提交反馈', exact: true}).waitFor();
  await page.getByText('验证通过，可以提交', {exact: true}).waitFor();
  await page.request.post(base + '/test/control', {data: {failNextWrite: true}});
  await page.getByRole('button', {name: '提交反馈', exact: true}).click();
  await page.locator('.inline-error').waitFor();
  check((await page.locator('.inline-error').innerText()).includes('模拟网络失败'), 'failed write shows a recoverable error');
  check((await page.locator('.action-preview').innerText()).includes('手机界面反馈草稿'), 'failed write keeps the original draft');
  await page.getByText('验证通过，可以提交', {exact: true}).waitFor();
  await page.getByRole('button', {name: '提交反馈', exact: true}).click();
  await page.locator('#modal').waitFor({state: 'hidden'});
  const writes = await (await page.request.get(base + '/test/writes')).json();
  const feedbackWrites = writes.slice(previousWriteCount).filter(item => item.path === '/api/feedback');
  check(feedbackWrites.length === 2 && feedbackWrites[0].key === feedbackWrites[1].key, 'retry reuses the same idempotency key');
  check(feedbackWrites[1].body.private && feedbackWrites[1].body.category === 'idea', 'submitted payload retains private flag and category');
  await page.getByRole('button', {name: '公告', exact: true}).click();
  await page.locator('.announcement-card').waitFor();
  await fit('phone announcements');
  check(await page.locator('.announcement-body a').getAttribute('href') === 'https://yunget.yunl.us.ci/', 'announcement links remain usable');
  await page.screenshot({animations: 'disabled', path: directory + '/announcements-light.png'});
  await page.getByRole('button', {name: '闲聊', exact: true}).click();
  await page.locator('.chat-message').first().waitFor();
  await page.locator('#chat-new').evaluate(button => button.click());
  await page.locator('#chat-body').fill('这条尚未发送的消息，刷新时不能被清空。');
  await page.locator('#chat-body').focus();
  await page.locator('#chat-log').evaluate(log => {log.scrollTop = 0;});
  await page.request.post(base + '/test/control', {data: {addChat: '自动刷新新增的示例消息'}});
  await page.getByRole('button', {name: /条新消息/}).waitFor({timeout: 18000});
  check(await page.locator('#chat-body').inputValue() === '这条尚未发送的消息，刷新时不能被清空。', 'automatic polling preserves the unsent message');
  check(await page.locator('#chat-body').evaluate(input => input === document.activeElement), 'automatic polling preserves keyboard focus');
  check(await page.locator('#chat-log').evaluate(log => log.scrollTop) < 20, 'new messages do not pull a reader away from history');
  await page.getByRole('button', {name: /条新消息/}).click();
  const chatFit = async name => {
    await fit(name);
    const geometry = await page.evaluate(() => {
      const log = document.getElementById('chat-log').getBoundingClientRect();
      const form = document.getElementById('chat-form').getBoundingClientRect();
      const send = document.querySelector('.send-button').getBoundingClientRect();
      const last = document.querySelector('.chat-message:last-child').getBoundingClientRect();
      return {logTop: log.top, logBottom: log.bottom, formTop: form.top, formBottom: form.bottom, sendBottom: send.bottom, lastBottom: last.bottom, viewport: innerHeight};
    });
    check(geometry.logBottom <= geometry.formTop + 1, name + ' composer never overlaps the message area');
    check(geometry.sendBottom <= geometry.viewport + 1 && geometry.formBottom <= geometry.viewport + 1, name + ' send button stays in the visible viewport');
    check(geometry.lastBottom <= geometry.logBottom + 2, name + ' last message is fully scrollable above the composer');
  };
  await chatFit('390px chat');
  await page.screenshot({animations: 'disabled', path: directory + '/chat-light.png'});
  await page.setViewportSize({width: 390, height: 430});
  await page.waitForTimeout(100);
  await chatFit('keyboard-height viewport');
  await page.screenshot({animations: 'disabled', path: directory + '/chat-keyboard-height.png'});
  await page.setViewportSize({width: 320, height: 568});
  await page.waitForTimeout(100);
  await chatFit('320px chat');
  await page.screenshot({animations: 'disabled', path: directory + '/chat-320.png'});
  await page.setViewportSize({width: 390, height: 844});
  await page.emulateMedia({colorScheme: 'dark', reducedMotion: 'reduce'});
  await page.screenshot({animations: 'disabled', path: directory + '/chat-dark.png'});
  await page.getByRole('button', {name: '反馈', exact: true}).click();
  await page.locator('.feedback-row').first().waitFor();
  await page.screenshot({animations: 'disabled', path: directory + '/feedback-dark.png'});
  await page.locator('.feedback-row').first().click();
  await page.locator('#reply').waitFor();
  await page.locator('#reply').fill('待发送的回复草稿');
  await page.getByRole('button', {name: '关闭', exact: true}).click();
  await page.locator('.feedback-row').first().click();
  await page.locator('#reply').waitFor();
  check(await page.locator('#reply').inputValue() === '待发送的回复草稿', 'thread reopening preserves the reply draft');
  await page.screenshot({animations: 'disabled', path: directory + '/thread-dark.png'});
  await page.keyboard.press('Escape');
  await page.locator('#modal').waitFor({state: 'hidden'});
  check(await page.locator('.feedback-row').first().evaluate(button => button === document.activeElement), 'modal returns keyboard focus to its opener');
  await page.emulateMedia({colorScheme: 'light', reducedMotion: 'no-preference'});
  await page.setViewportSize({width: 1440, height: 900});
  await fit('desktop feedback');
  await page.screenshot({animations: 'disabled', path: directory + '/desktop.png'});
  await page.goto(base + '/chat');
  await page.locator('#chat-body').waitFor();
  check(await page.locator('body').evaluate(body => body.classList.contains('chat-mode')), 'direct /chat URL opens the chat view');
  await page.goto(base + '/admin');
  await page.setViewportSize({width: 390, height: 844});
  await page.getByRole('heading', {name: '开发者后台', exact: true}).waitFor();
  await fit('phone developer backend');
  await page.getByRole('button', {name: '编辑', exact: true}).first().click();
  await page.locator('#announcement-title').waitFor();
  check((await page.locator('#announcement-title').inputValue()).includes('2.7.28'), 'announcement editor receives existing content');
  await page.screenshot({animations: 'disabled', path: directory + '/admin-editor.png'});
  await page.getByRole('button', {name: '关闭', exact: true}).click();
  check(errors.length === 0, 'no uncaught application errors: ' + errors.join(', '));
  check(external.length === 0, 'verification works without external script or service requests');
  return {checks, count: checks.length, errors};
}
